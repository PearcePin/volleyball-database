import json
import pandas as pd
from common import ROOT, engine, statements

def markdown(df):
    def clean(v):
        return str(v).replace('|','/').replace('\n',' ')
    rows=['| '+' | '.join(map(clean,df.columns))+' |','| '+' | '.join(['---']*len(df.columns))+' |']
    rows += ['| '+' | '.join(map(clean,row))+' |' for row in df.itertuples(index=False,name=None)]
    return '\n'.join(rows)

def main():
    dest=ROOT/'docs/query_results';dest.mkdir(exist_ok=True)
    titles=['Q1 Season team rankings','Q2 Player across seasons','Q3 Head-to-head history',
            'Q4 Top players','Q5a Five-set match details','Q5b Five-set proportions']
    report=['# Actual MySQL query results','', 'Generated by `python scripts/run_queries.py` against MySQL, using the exact statements in `sql/queries.sql`.',
            '', 'Tables below show up to 12 rows each. Full results are in `query_results/*.csv`.','']
    sizes={}
    with engine().connect() as conn:
        report += ['MySQL version: '+conn.exec_driver_sql('SELECT VERSION()').scalar_one(),'']
        index=0
        for sql in statements(ROOT/'sql/queries.sql'):
            result=conn.exec_driver_sql(sql)
            if '@team_b' in sql and not result.returns_rows and sql.lstrip().startswith('SET'):
                params=conn.exec_driver_sql('SELECT @season_id,@player_id,@team_a,@team_b').one()
                report += [f'Parameters: season_id={params[0]}, player_id={params[1]}, team_a={params[2]}, team_b={params[3]}.','']
            if result.returns_rows:
                df=pd.DataFrame(result.fetchall(),columns=result.keys())
                name=['q1','q2','q3','q4','q5a','q5b'][index]
                df.to_csv(dest/f'{name}.csv',index=False,encoding='utf-8-sig')
                sizes[name]=len(df)
                report += ['## '+titles[index],'',f'Returned {len(df)} rows.','',markdown(df.head(12)),'']
                print(f'{name}: {len(df)} rows'); index+=1
    (ROOT/'docs/query_results.md').write_text('\n'.join(report),encoding='utf-8')
    (dest/'row_counts.json').write_text(json.dumps(sizes,indent=2),encoding='utf-8')

if __name__=='__main__':
    main()
